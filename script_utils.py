def should_clear_model(prompt: str, fusion_state: dict) -> bool:
    """Return True if the prompt implies the user wants to start from scratch."""
    p = prompt.lower()
    explicit_reset = [
        "reset",
        "start over",
        "start new",
        "new design",
        "clear design",
        "from scratch",
        "delete everything",
    ]
    if any(phrase in p for phrase in explicit_reset):
        return True

    has_geometry = False
    if isinstance(fusion_state, dict):
        has_geometry = fusion_state.get("body_count", 0) > 0

    # model_summary is not available here; fall back to geometry presence only
    if not has_geometry:
        seed_words = [
            "create",
            "make",
            "build",
            "new",
            "cube",
            "box",
            "cylinder",
            "sphere",
        ]
        return any(word in p for word in seed_words)
    return False

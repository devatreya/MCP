def summarize_fusion_state(state: dict) -> str:
    """Return a human-readable summary of the Fusion 360 model state dict."""
    if not state:
        return "No state snapshot available."
    lines = []
    timestamp = state.get("timestamp", "unknown")
    units = state.get("units", "cm")
    lines.append(f"Last updated: {timestamp}")
    lines.append(
        f"Bodies: {state.get('body_count', 0)}, "
        f"Sketches: {state.get('sketch_count', 0)}, "
        f"Features: {state.get('feature_count', 0)}, "
        f"Units: {units}"
    )
    for body in state.get("bodies", []):
        name = body.get("name", "Body")
        bbox = body.get("bbox") or {}
        size_dict = bbox.get("size") or {}
        center_dict = bbox.get("center") or {}
        size = body.get("size_cm") or [
            size_dict.get("x", 0),
            size_dict.get("y", 0),
            size_dict.get("z", 0),
        ]
        center = body.get("center_cm") or [
            center_dict.get("x", 0),
            center_dict.get("y", 0),
            center_dict.get("z", 0),
        ]
        faces = body.get("face_count", 0)
        lines.append(
            f"- {name}: size {size[0]:.2f}x{size[1]:.2f}x{size[2]:.2f} cm, "
            f"center {center[0]:.2f},{center[1]:.2f},{center[2]:.2f} cm, "
            f"faces {faces}"
        )

    # Include origin construction planes so LLM knows they're available
    origin_planes = state.get("origin_planes", [])
    if origin_planes:
        lines.append("Origin planes:")
        for p in origin_planes:
            lines.append(f"  - {p['name']} → {p['code']} ({p['label']})")

    return "\n".join(lines)


def summarize_selection_context(selection: dict) -> str:
    """Return a human-readable summary of the active selection context dict."""
    if not selection:
        return "No active selections."

    if isinstance(selection, list):
        items = selection
        count = len(items)
    else:
        items = selection.get("items", []) if isinstance(selection, dict) else []
        count = selection.get("count", len(items)) if isinstance(selection, dict) else len(items)

    if count == 0:
        return "No active selections."

    lines = [f"Active selections: {count}"]
    for item in items[:8]:
        kind = item.get("kind", item.get("object_type", "unknown"))
        index = item.get("index", 0)
        if kind == "face":
            normal = item.get("normal") or [0, 0, 0]
            body_name = item.get("body_name", "body")
            area = item.get("area_cm2", 0)
            lines.append(
                f"- [{index}] face on {body_name}, normal {normal[0]:.3f},{normal[1]:.3f},{normal[2]:.3f}, area {area:.2f} cm^2"
            )
        elif kind == "body":
            lines.append(
                f"- [{index}] body {item.get('name', 'Body')}, volume {item.get('volume_cm3', 0):.2f} cm^3"
            )
        elif kind == "edge":
            lines.append(f"- [{index}] edge length {item.get('length_cm', 0):.2f} cm")
        elif kind == "vertex":
            point = item.get("point") or {}
            lines.append(
                f"- [{index}] vertex at {point.get('x', 0):.2f},{point.get('y', 0):.2f},{point.get('z', 0):.2f}"
            )
        elif kind == "constructionplane":
            plane_name = item.get("plane_name") or item.get("name", "unknown plane")
            lines.append(
                f"- [{index}] construction plane '{plane_name}' "
                f"(use: sketches.add(entity) where entity = ui.activeSelections.item({index}).entity)"
            )
        elif kind == "constructionaxis":
            axis_name = item.get("axis_name") or item.get("name", "unknown axis")
            lines.append(f"- [{index}] construction axis '{axis_name}'")
        else:
            lines.append(f"- [{index}] {kind}")

    if count > 8:
        lines.append(f"... {count - 8} more selections")

    return "\n".join(lines)


